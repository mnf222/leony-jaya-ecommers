drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
    on public.products for select
    to anon, authenticated
    using (is_active or (select public.is_admin()));

drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products"
    on public.products for all
    to authenticated
    using ((select public.is_admin()))
    with check ((select public.is_admin()));

drop policy if exists "Public can read images for visible products" on public.product_images;
create policy "Public can read images for visible products"
    on public.product_images for select
    to anon, authenticated
    using (
        exists (
            select 1
            from public.products
            where products.id = product_images.product_id
              and (products.is_active or (select public.is_admin()))
        )
    );

drop policy if exists "Admins can manage product images" on public.product_images;
create policy "Admins can manage product images"
    on public.product_images for all
    to authenticated
    using ((select public.is_admin()))
    with check ((select public.is_admin()));

drop policy if exists "Users can read their profile" on public.profiles;
create policy "Users can read their profile"
    on public.profiles for select
    to authenticated
    using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "Customers can update their own profile" on public.profiles;
create policy "Customers can update their own profile"
    on public.profiles for update
    to authenticated
    using (id = (select auth.uid()) and role = 'customer')
    with check (id = (select auth.uid()) and role = 'customer');

drop policy if exists "Users can read their orders" on public.orders;
create policy "Users can read their orders"
    on public.orders for select
    to authenticated
    using (user_id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "Admins can update order status and tracking" on public.orders;
create policy "Admins can update order status and tracking"
    on public.orders for update
    to authenticated
    using ((select public.is_admin()))
    with check ((select public.is_admin()));

drop policy if exists "Users can read their order items" on public.order_items;
create policy "Users can read their order items"
    on public.order_items for select
    to authenticated
    using (
        exists (
            select 1
            from public.orders
            where orders.id = order_items.order_id
              and (orders.user_id = (select auth.uid()) or (select public.is_admin()))
        )
    );

