create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    full_name text not null default '',
    phone text,
    role text not null default 'customer' check (role in ('customer', 'admin')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.profiles
    add column if not exists full_name text not null default '',
    add column if not exists phone text,
    add column if not exists role text not null default 'customer',
    add column if not exists created_at timestamptz not null default now(),
    add column if not exists updated_at timestamptz not null default now();

do $$
begin
    if not exists (
        select 1
        from pg_attribute
        where attrelid = 'public.profiles'::regclass
          and attname = 'id'
          and atttypid = 'uuid'::regtype
          and not attisdropped
    ) then
        raise exception 'public.profiles must have an id column of type uuid linked to auth.users. Inspect the existing table before migrating.';
    end if;
end;
$$;

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    slug text not null unique,
    description text,
    price bigint not null check (price >= 0),
    stock integer not null default 0 check (stock >= 0),
    size_guide text,
    article_color text not null default '#FFFFFF' check (article_color ~ '^#[A-Fa-f0-9]{6}$'),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists products_active_created_at_idx on public.products (is_active, created_at desc);

create table if not exists public.product_images (
    id bigint generated by default as identity primary key,
    product_id bigint not null references public.products (id) on delete cascade,
    image_url text not null check (length(image_url) <= 2048),
    is_primary boolean not null default false,
    created_at timestamptz not null default now()
);

create index if not exists product_images_product_id_idx on public.product_images (product_id);
create unique index if not exists product_images_one_primary_per_product_idx
    on public.product_images (product_id) where is_primary;

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles (id) on delete restrict,
    total_price bigint not null check (total_price >= 0),
    status text not null default 'pending'
        check (status in ('pending', 'paid', 'shipped', 'completed')),
    payment_method text check (payment_method in ('bank_transfer', 'qris', 'cod')),
    resi_number text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists orders_user_id_created_at_idx on public.orders (user_id, created_at desc);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders (id) on delete cascade,
    product_id bigint not null references public.products (id) on delete restrict,
    quantity integer not null check (quantity between 1 and 20),
    price bigint not null check (price >= 0),
    size text not null check (length(size) between 1 and 10),
    created_at timestamptz not null default now()
);

create index if not exists order_items_order_id_idx on public.order_items (order_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, full_name, phone)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', ''),
        nullif(new.raw_user_meta_data ->> 'phone', '')
    )
    on conflict (id) do update
    set full_name = case
            when public.profiles.full_name = '' then excluded.full_name
            else public.profiles.full_name
        end,
        phone = coalesce(public.profiles.phone, excluded.phone),
        updated_at = now();
    return new;
end;
$$;

drop trigger if exists leony_handle_new_user on auth.users;
drop trigger if exists on_auth_user_created on auth.users;

create trigger leony_handle_new_user
    after insert on auth.users
    for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
          and role = 'admin'
    );
$$;

create or replace function public.checkout_order(p_payment_method text, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_item jsonb;
    v_product public.products%rowtype;
    v_order public.orders%rowtype;
    v_product_id bigint;
    v_quantity integer;
    v_size text;
    v_total bigint := 0;
begin
    if v_user_id is null then
        raise exception 'You must be signed in to place an order.' using errcode = '42501';
    end if;

    if p_payment_method is null or p_payment_method not in ('bank_transfer', 'qris', 'cod') then
        raise exception 'Invalid payment method.' using errcode = '22023';
    end if;

    if jsonb_typeof(p_items) is distinct from 'array' then
        raise exception 'Items must be an array.' using errcode = '22023';
    end if;

    if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
        raise exception 'An order must contain between 1 and 50 items.' using errcode = '22023';
    end if;

    if exists (
        select 1
        from jsonb_array_elements(p_items) as item(value)
        where jsonb_typeof(item.value) is distinct from 'object'
           or coalesce(item.value ->> 'product_id', '') !~ '^[0-9]+$'
           or coalesce(item.value ->> 'quantity', '') !~ '^([1-9]|1[0-9]|20)$'
           or btrim(coalesce(item.value ->> 'size', '')) = ''
           or length(item.value ->> 'size') > 10
    ) then
        raise exception 'Each item requires a valid product_id, quantity, and size.' using errcode = '22023';
    end if;

    insert into public.orders (user_id, total_price, status, payment_method)
    values (v_user_id, 0, 'pending', p_payment_method)
    returning * into v_order;

    for v_item in
        select item.value
        from jsonb_array_elements(p_items) as item(value)
        order by (item.value ->> 'product_id')::bigint
    loop
        v_product_id := (v_item ->> 'product_id')::bigint;
        v_quantity := (v_item ->> 'quantity')::integer;
        v_size := btrim(v_item ->> 'size');

        select *
        into v_product
        from public.products
        where id = v_product_id
          and is_active
        for update;

        if not found then
            raise exception 'A product in this order is unavailable.' using errcode = '22023';
        end if;

        if v_product.stock < v_quantity then
            raise exception 'Insufficient stock for %.', v_product.name using errcode = '22023';
        end if;

        update public.products
        set stock = stock - v_quantity,
            updated_at = now()
        where id = v_product.id;

        insert into public.order_items (order_id, product_id, quantity, price, size)
        values (v_order.id, v_product.id, v_quantity, v_product.price, v_size);

        v_total := v_total + v_product.price * v_quantity;
    end loop;

    update public.orders
    set total_price = v_total,
        updated_at = now()
    where id = v_order.id
    returning * into v_order;

    return jsonb_build_object(
        'id', v_order.id,
        'total_price', v_order.total_price,
        'status', v_order.status,
        'payment_method', v_order.payment_method,
        'created_at', v_order.created_at
    );
end;
$$;

