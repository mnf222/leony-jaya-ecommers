-- ---------------------------------------------------------------------------
-- 2. Per-size stock. products.stock becomes the sum of its variants (kept in sync by trigger).
-- ---------------------------------------------------------------------------
create table if not exists public.product_variants (
    id bigint generated by default as identity primary key,
    product_id bigint not null references public.products (id) on delete cascade,
    size text not null check (length(btrim(size)) between 1 and 10),
    stock integer not null default 0 check (stock >= 0),
    created_at timestamptz not null default now(),
    unique (product_id, size)
);

create index if not exists product_variants_product_id_idx on public.product_variants (product_id);

create or replace function public.sync_product_stock()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_product_id bigint := coalesce(new.product_id, old.product_id);
begin
    update public.products
    set stock = coalesce((select sum(v.stock) from public.product_variants v where v.product_id = v_product_id), 0),
        updated_at = now()
    where id = v_product_id;
    return null;
end;
$$;

drop trigger if exists product_variants_sync_stock on public.product_variants;
create trigger product_variants_sync_stock
    after insert or update or delete on public.product_variants
    for each row execute function public.sync_product_stock();

-- Backfill: take sizes from each product's size_guide ("30 - Waist 76cm | ..."), falling back to
-- 28/30/32/34, and split the current stock evenly (remainder goes to the first size).
-- Adjust the numbers per size in the admin dashboard afterwards.
with parsed as (
    select p.id as product_id, p.stock, btrim(r.m[1]) as size, r.rn
    from public.products p,
         lateral regexp_matches(coalesce(p.size_guide, ''), '^\s*([A-Za-z0-9]+)\s*[-–:|]', 'gn')
             with ordinality as r(m, rn)
),
fallback as (
    select p.id as product_id, p.stock, x.size, x.rn
    from public.products p,
         unnest(array['28', '30', '32', '34']) with ordinality as x(size, rn)
    where not exists (select 1 from parsed where parsed.product_id = p.id)
),
all_sizes as (
    select * from parsed
    union all
    select * from fallback
),
sized as (
    select product_id, stock, size, rn, count(*) over (partition by product_id) as n
    from all_sizes
)
insert into public.product_variants (product_id, size, stock)
select product_id,
       size,
       (stock / n) + case when rn = 1 then stock % n else 0 end
from sized
where not exists (select 1 from public.product_variants v where v.product_id = sized.product_id)
on conflict (product_id, size) do nothing;

alter table public.product_variants enable row level security;

drop policy if exists "Public can read variants of visible products" on public.product_variants;
create policy "Public can read variants of visible products"
    on public.product_variants for select
    to anon, authenticated
    using (
        exists (
            select 1 from public.products
            where products.id = product_variants.product_id
              and (products.is_active or (select public.is_admin()))
        )
    );

drop policy if exists "Admins can manage variants" on public.product_variants;
create policy "Admins can manage variants"
    on public.product_variants for all
    to authenticated
    using ((select public.is_admin()))
    with check ((select public.is_admin()));

grant select on public.product_variants to anon, authenticated;
grant insert, update, delete on public.product_variants to authenticated;

-- ---------------------------------------------------------------------------
-- 3. Order status rules + automatic restock on cancel
-- ---------------------------------------------------------------------------
create or replace function public.guard_order_status()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    if new.status = old.status then
        return new;
    end if;

    if (old.status = 'pending' and new.status in ('paid', 'cancelled'))
       or (old.status = 'pending' and new.status = 'shipped' and old.payment_method = 'cod')
       or (old.status = 'paid' and new.status in ('shipped', 'cancelled'))
       or (old.status = 'shipped' and new.status = 'completed') then
        new.updated_at := now();
        return new;
    end if;

    raise exception 'Invalid status change from % to %.', old.status, new.status using errcode = '22023';
end;
$$;

drop trigger if exists orders_guard_status on public.orders;
create trigger orders_guard_status
    before update of status on public.orders
    for each row execute function public.guard_order_status();

create or replace function public.restock_cancelled_order()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if new.status = 'cancelled' and old.status <> 'cancelled' then
        update public.product_variants v
        set stock = v.stock + o.qty
        from (
            select product_id, size, sum(quantity)::integer as qty
            from public.order_items
            where order_id = new.id
            group by product_id, size
        ) o
        where v.product_id = o.product_id
          and v.size = o.size;
    end if;
    return null;
end;
$$;

drop trigger if exists orders_restock_on_cancel on public.orders;
create trigger orders_restock_on_cancel
    after update of status on public.orders
    for each row execute function public.restock_cancelled_order();

-- ---------------------------------------------------------------------------
-- 4. Checkout (now takes shipping details and checks stock per size)
-- ---------------------------------------------------------------------------
drop function if exists public.checkout_order(text, jsonb);
drop function if exists public.checkout_order(text, jsonb, jsonb);

create or replace function public.checkout_order(p_payment_method text, p_items jsonb, p_shipping jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_line record;
    v_product public.products%rowtype;
    v_variant public.product_variants%rowtype;
    v_order public.orders%rowtype;
    v_total bigint := 0;
    v_name text;
    v_phone text;
    v_address text;
begin
    if v_user_id is null then
        raise exception 'You must be signed in to place an order.' using errcode = '42501';
    end if;

    if p_payment_method is null or p_payment_method not in ('bank_transfer', 'qris', 'cod') then
        raise exception 'Invalid payment method.' using errcode = '22023';
    end if;

    if jsonb_typeof(p_shipping) is distinct from 'object' then
        raise exception 'Shipping details are required.' using errcode = '22023';
    end if;
    v_name := btrim(coalesce(p_shipping ->> 'name', ''));
    v_phone := btrim(coalesce(p_shipping ->> 'phone', ''));
    v_address := btrim(coalesce(p_shipping ->> 'address', ''));
    if length(v_name) not between 2 and 100
       or v_phone !~ '^\+?[0-9][0-9 -]{7,18}$'
       or length(v_address) not between 10 and 500 then
        raise exception 'Shipping details are invalid.' using errcode = '22023';
    end if;

    if jsonb_typeof(p_items) is distinct from 'array' then
        raise exception 'Items must be an array.' using errcode = '22023';
    end if;
    if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
        raise exception 'An order must contain between 1 and 50 items.' using errcode = '22023';
    end if;
    if exists (
        select 1
        from jsonb_array_elements(p_items) as item(value)
        where jsonb_typeof(item.value) is distinct from 'object'
           or coalesce(item.value ->> 'product_id', '') !~ '^[0-9]+$'
           or coalesce(item.value ->> 'quantity', '') !~ '^([1-9]|1[0-9]|20)$'
           or btrim(coalesce(item.value ->> 'size', '')) = ''
           or length(item.value ->> 'size') > 10
    ) then
        raise exception 'Each item requires a valid product_id, quantity, and size.' using errcode = '22023';
    end if;

    insert into public.orders (
        user_id, total_price, status, payment_method,
        shipping_name, shipping_phone, shipping_address, expires_at
    )
    values (
        v_user_id, 0, 'pending', p_payment_method,
        v_name, v_phone, v_address,
        case when p_payment_method = 'cod' then null else now() + interval '24 hours' end
    )
    returning * into v_order;

    -- Same product + size on several lines is merged; locks are taken in a fixed order (no deadlocks).
    for v_line in
        select (item.value ->> 'product_id')::bigint as product_id,
               btrim(item.value ->> 'size') as size,
               sum((item.value ->> 'quantity')::integer)::integer as quantity
        from jsonb_array_elements(p_items) as item(value)
        group by 1, 2
        order by 1, 2
    loop
        if v_line.quantity > 20 then
            raise exception 'You can order at most 20 of one item.' using errcode = '22023';
        end if;

        select * into v_product
        from public.products
        where id = v_line.product_id and is_active;
        if not found then
            raise exception 'A product in this order is unavailable.' using errcode = '22023';
        end if;

        select * into v_variant
        from public.product_variants
        where product_id = v_line.product_id and size = v_line.size
        for update;
        if not found then
            raise exception 'Size % is not available for %.', v_line.size, v_product.name using errcode = '22023';
        end if;

        if v_variant.stock < v_line.quantity then
            raise exception 'Insufficient stock for % (size %).', v_product.name, v_line.size using errcode = '22023';
        end if;

        update public.product_variants
        set stock = stock - v_line.quantity
        where id = v_variant.id;

        insert into public.order_items (order_id, product_id, quantity, price, size)
        values (v_order.id, v_product.id, v_line.quantity, v_product.price, v_line.size);

        v_total := v_total + v_product.price * v_line.quantity;
    end loop;

    update public.orders
    set total_price = v_total, updated_at = now()
    where id = v_order.id
    returning * into v_order;

    return jsonb_build_object(
        'id', v_order.id,
        'total_price', v_order.total_price,
        'status', v_order.status,
        'payment_method', v_order.payment_method,
        'created_at', v_order.created_at,
        'expires_at', v_order.expires_at
    );
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. Customer actions: cancel a pending order, attach a payment proof
-- ---------------------------------------------------------------------------
create or replace function public.cancel_order(p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_order public.orders%rowtype;
begin
    select * into v_order from public.orders where id = p_order_id for update;
    if not found or (v_order.user_id is distinct from auth.uid() and not public.is_admin()) then
        raise exception 'Order not found.' using errcode = '22023';
    end if;
    if v_order.status <> 'pending' then
        raise exception 'Only pending orders can be cancelled.' using errcode = '22023';
    end if;

    update public.orders set status = 'cancelled' where id = v_order.id;
    return jsonb_build_object('id', v_order.id, 'status', 'cancelled');
end;
$$;

create or replace function public.submit_payment_proof(p_order_id bigint, p_path text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_order public.orders%rowtype;
begin
    if v_user_id is null then
        raise exception 'You must be signed in.' using errcode = '42501';
    end if;

    select * into v_order from public.orders where id = p_order_id and user_id = v_user_id for update;
    if not found then
        raise exception 'Order not found.' using errcode = '22023';
    end if;
    if v_order.status <> 'pending' or v_order.payment_method = 'cod' then
        raise exception 'This order does not need a payment proof.' using errcode = '22023';
    end if;
    if p_path is null or p_path not like v_user_id::text || '/%' or length(p_path) > 300 then
        raise exception 'Invalid proof file.' using errcode = '22023';
    end if;
    if not exists (select 1 from storage.objects where bucket_id = 'payment-proofs' and name = p_path) then
        raise exception 'Proof file was not uploaded.' using errcode = '22023';
    end if;

    update public.orders
    set payment_proof_path = p_path,
        proof_uploaded_at = now(),
        expires_at = now() + interval '72 hours',  -- give the admin time to verify
        updated_at = now()
    where id = v_order.id;

    return jsonb_build_object('id', v_order.id, 'payment_proof_path', p_path);
end;
$$;

-- Cancels unpaid, expired orders (and thereby restocks them). Called by pg_cron or manually.
create or replace function public.expire_pending_orders()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_count integer;
begin
    update public.orders
    set status = 'cancelled'
    where status = 'pending'
      and payment_method <> 'cod'
      and expires_at is not null
      and expires_at < now();
    get diagnostics v_count = row_count;
    return v_count;
end;
$$;

revoke all on function public.cancel_order(bigint) from public, anon;
revoke all on function public.submit_payment_proof(bigint, text) from public, anon;
revoke all on function public.expire_pending_orders() from public, anon, authenticated;
revoke all on function public.checkout_order(text, jsonb, jsonb) from public, anon;
revoke all on function public.sync_product_stock() from public, anon, authenticated;
revoke all on function public.restock_cancelled_order() from public, anon, authenticated;
revoke all on function public.guard_order_status() from public, anon, authenticated;
grant execute on function public.checkout_order(text, jsonb, jsonb) to authenticated;
grant execute on function public.cancel_order(bigint) to authenticated;
grant execute on function public.submit_payment_proof(bigint, text) to authenticated;

-- Hourly expiry job, only if the pg_cron extension is enabled for this project
-- (Dashboard > Database > Extensions > pg_cron). Otherwise skipped silently.
do $$
begin
    create extension if not exists pg_cron;
    perform cron.schedule('expire-pending-orders', '0 * * * *', 'select public.expire_pending_orders()');
exception when others then
    raise notice 'pg_cron not available; call public.expire_pending_orders() some other way (%).', sqlerrm;
end;
$$;

